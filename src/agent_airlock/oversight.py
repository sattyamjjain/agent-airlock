"""Human-oversight decorator (v0.8.4+, Code-as-Harness survey anchor).

What this module ships
----------------------
A decorator factory ``@requires_human_oversight(approver=...)`` that
gates a tool function on an operator-supplied approval callable.
The decorator builds a structured :class:`OversightRequest`, hands
it to the approver, and acts on the returned
:class:`OversightResponse` — calling the wrapped function on
``GRANT``, raising :class:`OversightDeniedError` on ``DENY``, or
:class:`OversightTimeoutError` on ``TIMEOUT``.

What this module does NOT ship
------------------------------
- An ``audit_emitter.await_response`` bidirectional RPC channel.
  The 2026-05-20 Product Improvements doc proposed grafting a
  request/response channel onto the existing one-way audit emitter.
  That would have invented a new transport abstraction inside
  agent-airlock. Instead, the **operator supplies the transport**
  via the ``approver`` callable; agent-airlock ships the decorator
  + data shapes only.
- Slack / PagerDuty / CLI integration. Operators wire these into
  their own approver callable.
- Async wrapping. v0.8.4 ships the sync surface. Async support is
  a deferred follow-up that needs a separate API design pass.

Why the operator-supplied-approver shape
----------------------------------------
agent-airlock's existing primitives are all building blocks
operators compose (``vaccinate_openapi(spec)``,
``classify_sdk_lineage(...)``, ``OpenAPIDriftGuard(spec=...)``).
This decorator follows the same pattern: agent-airlock provides
the gate + the protocol shapes; the operator wires the transport.

Anchor
------
Code-as-Harness survey (arXiv:2605.18747, Ning et al., 2026-05-18)
identifies "human oversight for safety-critical actions" as an
open challenge in harness engineering. This module is a primitive
operators can use to address that challenge for tool calls in
their own harness.

Primary source
--------------
https://arxiv.org/abs/2605.18747
"""

from __future__ import annotations

import asyncio
import contextlib
import contextvars
import datetime as _dt
import enum
import functools
import inspect
import math
import threading
import uuid
from collections.abc import Callable, Mapping
from dataclasses import dataclass, field
from typing import Any, Literal, TypeVar

from ._log import structlog

logger = structlog.get_logger("agent-airlock.oversight")


F = TypeVar("F", bound=Callable[..., Any])


class OversightVerdict(str, enum.Enum):
    """Stable verdict labels returned by an approver."""

    GRANT = "grant"
    DENY = "deny"
    TIMEOUT = "timeout"


@dataclass(frozen=True)
class OversightRequest:
    """Structured approval request handed to the operator-supplied approver.

    Attributes:
        request_id: A UUID4 string (generated by the decorator) that
            the approver MUST echo on its :class:`OversightResponse`.
        tool_name: ``__name__`` of the wrapped function.
        args: Dict with two keys: ``"args"`` (positional, tuple) and
            ``"kwargs"`` (keyword, mapping). The approver inspects
            this to decide whether to grant.
        channel: Free-form hint passed through from the decorator
            ``channel=`` argument (e.g. ``"prod-deploys"``,
            ``"finance"``). The approver interprets this however
            its transport requires.
        timeout_seconds: Wall-clock timeout the operator declared
            on the decorator. Echoed onto the request so the
            approver can use it for its own poll loops if it wants.
        requested_at: ISO 8601 UTC timestamp when the gate fired.
        args_digest: The sha256 of the call's bound arguments in canonical JSON
            (:func:`agent_airlock.approvals.args_digest`). Echo it on the response to
            bind the decision to these arguments: a response naming another digest is
            refused. None only on a request built outside this package.
        args_preview: The bound arguments by name, each masked as an audit preview is
            (a value under a secret-sounding name replaced outright), for a human to read.
        agent_id: The calling agent's id, when the call carries one.
        session_id: The call's session id, when it carries one.
        policy_digest: The digest of the ``SecurityPolicy`` that escalated, so a decision
            stored with it can be checked against the policy in force on resume.
        expires_at: ISO 8601 UTC time after which no answer is taken
            (``requested_at`` plus the timeout).

    The last six fields arrived in 0.10.29, with defaults, so an approver written for
    0.10.28 keeps working.
    """

    request_id: str
    tool_name: str
    args: Mapping[str, Any]
    channel: str
    timeout_seconds: float
    requested_at: str
    args_digest: str | None = None
    args_preview: Mapping[str, str] = field(default_factory=dict)
    agent_id: str | None = None
    session_id: str | None = None
    policy_digest: str | None = None
    expires_at: str | None = None


@dataclass(frozen=True)
class OversightResponse:
    """Approver's reply.

    Attributes:
        request_id: MUST match the originating
            :attr:`OversightRequest.request_id`. A mismatch is treated
            as a protocol fault and raises ``ValueError``.
        verdict: :class:`OversightVerdict.GRANT` / ``DENY`` / ``TIMEOUT``.
        detail: Free-form explanation suitable for audit logs.
        approver: Optional identifier of the human/system that
            decided (e.g. ``"alice@example.com"``, ``"pagerduty-bot"``).
        args_digest: Optional echo of :attr:`OversightRequest.args_digest`: the
            arguments the decision was made about. One that differs from the request's
            is refused (0.10.29); None binds nothing and is read as before.
    """

    request_id: str
    verdict: OversightVerdict
    detail: str = ""
    approver: str | None = None
    args_digest: str | None = None


Approver = Callable[[OversightRequest], OversightResponse]
"""The operator-supplied callable signature."""


@dataclass(frozen=True)
class _ApproverOutcome:
    """What an approver did within its deadline.

    ``kind`` is ``"answered"`` (``value`` is what it returned, unchecked), ``"raised"``
    (``error``) or ``"timeout"`` (no answer in time: any later answer is dropped).
    """

    kind: Literal["answered", "raised", "timeout"]
    value: Any = None
    error: BaseException | None = None


def _deadline(timeout_seconds: float) -> float | None:
    """``timeout_seconds`` as a wait bound: None for no bound, never below 0."""
    if math.isinf(timeout_seconds):
        return None
    return max(0.0, timeout_seconds)


def _call_with_deadline(
    approver: Callable[[OversightRequest], Any],
    request: OversightRequest,
    timeout_seconds: float,
) -> _ApproverOutcome:
    """Call ``approver(request)`` in a worker thread and wait at most ``timeout_seconds``.

    Until 0.10.29 the approver ran inline and the timeout was only echoed on the request,
    so an approver that hung held the call (and, on the async path, the event loop) for as
    long as it hung. A late answer is now dropped: the thread runs on, but nothing reads
    what it returns. The thread is a daemon, so a hung approver never holds up interpreter
    exit, and runs in a copy of the caller's context. A coroutine returned here (an
    ``async`` approver on the sync path) is closed, never run, and comes back as the
    answer, which the caller reads as no approval.
    """
    box: list[_ApproverOutcome] = []

    def run() -> None:
        try:
            box.append(_ApproverOutcome("answered", value=approver(request)))
        except BaseException as exc:  # noqa: BLE001 - reported to the caller, not raised here
            box.append(_ApproverOutcome("raised", error=exc))

    context = contextvars.copy_context()
    worker = threading.Thread(target=context.run, args=(run,), name="airlock-approver", daemon=True)
    worker.start()
    worker.join(_deadline(timeout_seconds))
    if not box:
        return _ApproverOutcome("timeout")
    outcome = box[0]
    if outcome.kind == "answered" and inspect.iscoroutine(outcome.value):
        outcome.value.close()
    return outcome


async def _await_with_deadline(
    approver: Callable[[OversightRequest], Any],
    request: OversightRequest,
    timeout_seconds: float,
) -> _ApproverOutcome:
    """The async path's :func:`_call_with_deadline`: the event loop is never blocked.

    A sync approver runs in a daemon worker thread whose answer is handed back to the loop;
    an ``async`` approver (or an awaitable a sync one returns) is awaited with what is left
    of the deadline and cancelled when it runs out.
    """
    loop = asyncio.get_running_loop()
    ends = None if math.isinf(timeout_seconds) else loop.time() + max(0.0, timeout_seconds)
    try:
        if inspect.iscoroutinefunction(approver):
            outcome = _ApproverOutcome("answered", value=approver(request))
        else:
            outcome = await asyncio.wait_for(_threaded(loop, approver, request), _left(loop, ends))
        if outcome.kind == "answered" and inspect.isawaitable(outcome.value):
            value = await asyncio.wait_for(outcome.value, _left(loop, ends))
            outcome = _ApproverOutcome("answered", value=value)
    except asyncio.TimeoutError:
        return _ApproverOutcome("timeout")
    except Exception as exc:  # noqa: BLE001 - an async approver that raised
        return _ApproverOutcome("raised", error=exc)
    return outcome


def _left(loop: asyncio.AbstractEventLoop, ends: float | None) -> float | None:
    """Seconds left before ``ends`` on ``loop``'s clock (None: no deadline)."""
    return None if ends is None else max(0.0, ends - loop.time())


def _threaded(
    loop: asyncio.AbstractEventLoop,
    approver: Callable[[OversightRequest], Any],
    request: OversightRequest,
) -> asyncio.Future[_ApproverOutcome]:
    """A future the approver's answer, from a daemon worker thread, settles."""
    future: asyncio.Future[_ApproverOutcome] = loop.create_future()

    def settle(outcome: _ApproverOutcome) -> None:
        if not future.done():
            future.set_result(outcome)

    def run() -> None:
        try:
            outcome = _ApproverOutcome("answered", value=approver(request))
        except BaseException as exc:  # noqa: BLE001 - reported to the caller, not raised here
            outcome = _ApproverOutcome("raised", error=exc)
        with contextlib.suppress(RuntimeError):  # the loop closed before a late answer
            loop.call_soon_threadsafe(settle, outcome)

    context = contextvars.copy_context()
    threading.Thread(target=context.run, args=(run,), name="airlock-approver", daemon=True).start()
    return future


AuditEmitter = Callable[[str, Mapping[str, Any]], None]
"""Optional one-way emitter for ``oversight.request|grant|deny`` events.

This is a *one-way* sink, matching agent-airlock's existing emitter
shape. It does NOT support request/response RPC — that lives in the
:class:`Approver` callable.
"""


class OversightDeniedError(Exception):
    """Raised by a decorated function when the approver returns ``DENY``.

    Attributes:
        request: The :class:`OversightRequest` that was denied.
        response: The :class:`OversightResponse` that denied it.
    """

    def __init__(self, request: OversightRequest, response: OversightResponse) -> None:
        self.request = request
        self.response = response
        super().__init__(
            f"tool {request.tool_name!r} denied by oversight (approver={response.approver!r}): "
            f"{response.detail}"
        )


class OversightTimeoutError(TimeoutError):
    """Raised when the approver returns ``TIMEOUT`` (or doesn't respond in time).

    Attributes:
        request: The :class:`OversightRequest` that timed out.
    """

    def __init__(self, request: OversightRequest) -> None:
        self.request = request
        super().__init__(
            f"oversight gate timed out for tool {request.tool_name!r} "
            f"after {request.timeout_seconds:.1f}s"
        )


def requires_human_oversight(
    *,
    approver: Approver,
    channel: str = "default",
    timeout_seconds: float = 300.0,
    audit_emitter: AuditEmitter | None = None,
) -> Callable[[F], F]:
    """Decorator factory: gate a tool function on operator-supplied approval.

    Args:
        approver: Operator-supplied callable that receives an
            :class:`OversightRequest` and returns an
            :class:`OversightResponse`. The operator wires this to
            whatever transport they want (Slack, PagerDuty, CLI
            prompt, in-process recorded responses for tests, …).
        channel: Free-form hint passed through to the approver on
            :attr:`OversightRequest.channel`. Useful for routing
            in transports that have multiple endpoints.
        timeout_seconds: Wall-clock budget for the approver, echoed on
            :attr:`OversightRequest.timeout_seconds` and enforced: the
            approver runs in a worker thread, and no answer within the
            budget raises :class:`OversightTimeoutError` (a later answer
            is dropped). Until 0.10.29 it was only echoed.
        audit_emitter: Optional one-way callable that receives
            ``("oversight.request"|"oversight.grant"|"oversight.deny",
            payload_dict)`` for every gate firing. Useful for OTel /
            JSON-Lines audit trails. Defaults to ``None`` (events
            still go through the module structlog logger).

    Returns:
        A decorator that wraps any sync callable.

    Raises:
        TypeError: ``approver`` is not callable.
        ValueError: ``timeout_seconds`` is negative.
    """
    if not callable(approver):
        raise TypeError(f"approver must be callable; got {type(approver).__name__}")
    if timeout_seconds < 0.0:
        raise ValueError(f"timeout_seconds must be non-negative; got {timeout_seconds!r}")

    def decorator(fn: F) -> F:
        @functools.wraps(fn)
        def wrapped(*args: Any, **kwargs: Any) -> Any:
            request = _decorator_request(fn, args, kwargs, channel, float(timeout_seconds))
            _emit(
                audit_emitter,
                "oversight.request",
                {
                    "request_id": request.request_id,
                    "tool_name": request.tool_name,
                    "channel": request.channel,
                    "timeout_seconds": request.timeout_seconds,
                    "requested_at": request.requested_at,
                },
            )

            outcome = _call_with_deadline(approver, request, timeout_seconds)
            if outcome.kind == "raised" and outcome.error is not None:
                raise outcome.error
            response = outcome.value
            if outcome.kind == "timeout" or not _is_readable(response):
                _emit_unanswered(audit_emitter, request, outcome.kind, response)
                raise OversightTimeoutError(request=request)
            if response.request_id != request.request_id:
                raise ValueError(
                    f"approver returned a response with mismatched request_id: "
                    f"expected {request.request_id!r}, got {response.request_id!r}"
                )
            _check_echo(request, response)

            if response.verdict is OversightVerdict.GRANT:
                if _bound_digest(fn, args, kwargs) != request.args_digest:
                    raise ValueError("the call's arguments changed after the approval was asked")
                _emit(
                    audit_emitter,
                    "oversight.grant",
                    {
                        "request_id": request.request_id,
                        "tool_name": request.tool_name,
                        "approver": response.approver,
                        "detail": response.detail,
                    },
                )
                return fn(*args, **kwargs)

            if response.verdict is OversightVerdict.DENY:
                _emit(
                    audit_emitter,
                    "oversight.deny",
                    {
                        "request_id": request.request_id,
                        "tool_name": request.tool_name,
                        "approver": response.approver,
                        "detail": response.detail,
                    },
                )
                raise OversightDeniedError(request=request, response=response)

            # OversightVerdict.TIMEOUT
            _emit(
                audit_emitter,
                "oversight.timeout",
                {
                    "request_id": request.request_id,
                    "tool_name": request.tool_name,
                    "timeout_seconds": request.timeout_seconds,
                },
            )
            raise OversightTimeoutError(request=request)

        return wrapped  # type: ignore[return-value]

    return decorator


def _bound_arguments(fn: Callable[..., Any], args: Any, kwargs: Any) -> dict[str, Any]:
    """The decorated call's arguments by parameter name, or as given when they do not bind."""
    try:
        return dict(inspect.signature(fn).bind_partial(*args, **kwargs).arguments)
    except (TypeError, ValueError):
        return {"args": list(args), "kwargs": dict(kwargs)}


def _bound_digest(fn: Callable[..., Any], args: Any, kwargs: Any) -> str | None:
    """:func:`~agent_airlock.approvals.args_digest` of the call, None when unreadable."""
    from .approvals import args_digest

    try:
        return args_digest(_bound_arguments(fn, args, kwargs))
    except ValueError:
        return None


def _decorator_request(
    fn: Callable[..., Any], args: Any, kwargs: Any, channel: str, timeout_seconds: float
) -> OversightRequest:
    """The request ``@requires_human_oversight`` asks, bound to the call's arguments."""
    from .audit import AuditLogger

    now = _dt.datetime.now(_dt.timezone.utc)
    return OversightRequest(
        request_id=str(uuid.uuid4()),
        tool_name=fn.__name__,
        args={"args": args, "kwargs": dict(kwargs)},
        channel=channel,
        timeout_seconds=timeout_seconds,
        requested_at=now.isoformat(),
        args_digest=_bound_digest(fn, args, kwargs),
        args_preview=AuditLogger._redact_args(_bound_arguments(fn, args, kwargs)),
        expires_at=(now + _dt.timedelta(seconds=timeout_seconds)).isoformat(),
    )


def _check_echo(request: OversightRequest, response: OversightResponse) -> None:
    """Raise when the decision names arguments other than the request's.

    Raises:
        ValueError: The response echoes an ``args_digest`` other than the request's.
    """
    if response.args_digest is not None and response.args_digest != request.args_digest:
        raise ValueError(
            "approver returned a decision about other arguments: expected args_digest "
            f"{request.args_digest!r}, got {response.args_digest!r}"
        )


def _is_readable(response: Any) -> bool:
    """Whether ``response`` is an :class:`OversightResponse` whose verdict is a member.

    A str such as ``"grant"`` compares equal to ``OversightVerdict.GRANT`` (the enum is a
    ``str`` enum), so membership is checked with ``isinstance``, never ``==``.
    """
    return isinstance(response, OversightResponse) and isinstance(
        response.verdict, OversightVerdict
    )


def _emit_unanswered(
    emitter: AuditEmitter | None,
    request: OversightRequest,
    kind: str,
    response: Any,
) -> None:
    """Emit ``oversight.timeout`` for no answer in time, ``oversight.indeterminate`` for an
    answer that is not a readable approval (type names only, never the content)."""
    if kind == "timeout":
        _emit(
            emitter,
            "oversight.timeout",
            {
                "request_id": request.request_id,
                "tool_name": request.tool_name,
                "timeout_seconds": request.timeout_seconds,
            },
        )
        return
    verdict = (
        getattr(response, "verdict", None) if isinstance(response, OversightResponse) else None
    )
    _emit(
        emitter,
        "oversight.indeterminate",
        {
            "request_id": request.request_id,
            "tool_name": request.tool_name,
            "returned": type(response).__name__,
            "verdict_type": type(verdict).__name__,
        },
    )


def _emit(
    emitter: AuditEmitter | None,
    event_type: str,
    payload: Mapping[str, Any],
) -> None:
    """Fan out one structured event to the operator emitter + the module logger."""
    logger.info(event_type.replace(".", "_"), **payload)
    if emitter is not None:
        emitter(event_type, dict(payload))


@dataclass
class InProcessRecordedApprover:
    """Bundled testing helper — returns pre-set verdicts per tool name.

    Designed for unit-test scaffolding. Holds a ``decisions`` mapping
    of ``tool_name -> OversightVerdict``. When asked about a tool not
    in the mapping, defaults to :attr:`OversightVerdict.TIMEOUT` so
    tests fail loudly on unexpected calls rather than silently passing.

    The approver also records every :class:`OversightRequest` it
    received on the ``calls`` list, so tests can assert call shapes.

    Attributes:
        decisions: ``{tool_name: OversightVerdict}``.
        calls: Append-only list of every request received.
    """

    decisions: Mapping[str, OversightVerdict]
    calls: list[OversightRequest] = field(default_factory=list)

    def __call__(self, request: OversightRequest) -> OversightResponse:
        self.calls.append(request)
        verdict = self.decisions.get(request.tool_name, OversightVerdict.TIMEOUT)
        return OversightResponse(
            request_id=request.request_id,
            verdict=verdict,
            detail=f"InProcessRecordedApprover: {verdict.value}",
            approver="InProcessRecordedApprover",
        )


